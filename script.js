function byId(id) {
  return cards.find((card) => card.id === id);
}

function normalize(value) {
  return value.toLocaleLowerCase("de-AT");
}

function getCardDeck(card) {
  return card.deck || (card.scriptPage <= 82 ? "old" : "new");
}

function getDeckCards() {
  return cards.filter((card) => state.deck === "all" || getCardDeck(card) === state.deck);
}

function getKnownCount(cardSet = getDeckCards()) {
  return cardSet.filter((card) => state.learned.has(card.id)).length;
}

function getVisibleCards() {
  const query = normalize(state.query.trim());
  return state.order
    .map(byId)
    .filter(Boolean)
    .filter((card) => state.deck === "all" || getCardDeck(card) === state.deck)
    .filter((card) => state.topic === "Alle" || card.topic === state.topic)
    .filter((card) => {
      if (!query) return true;
      const haystack = normalize([
        card.question,
        card.topic,
        card.answer.join(" "),
        deckLabels[getCardDeck(card)],
        `skriptseite ${card.scriptPage}`,
        `seite ${card.scriptPage}`
      ].join(" "));
      return haystack.includes(query);
    });
}

function getGlossaryEntries(card) {
  const definitions = card.deck === "circulation" ? { ...glossary, ...nerveCirculationGlossary } : glossary;
  const explicitTerms = card.terms || [];
  const topicFallbacks = {
    "Abbildungen": [],
    "Binde- und Stützgewebe": ["Bindegewebe", "Stützgewebe", "Interzellularsubstanz"],
    "Drüsengewebe": ["Drüse", "Sekret", "Exokrin", "Endokrin"],
    "Epithelgewebe": ["Epithelgewebe", "Oberflächenepithel", "Drüsenepithel"],
    "Fettgewebe": ["Adipozyten", "Baufett", "Speicherfett"],
    "Gelenke": ["Gelenk", "Gelenkskapsel", "Synovia"],
    "Gewebe des Körpers": ["Gewebe", "Stroma", "Parenchym"],
    "Knorpel": ["Knorpel", "Chondrozyten", "Interzellularsubstanz"],
    "Knochen": ["Knochen", "Kompakta", "Spongiosa"],
    "Knochenmark": ["Knochenmark", "Blutbildung", "Erythrozyten"],
    "Muskelgewebe": ["Muskelgewebe", "Kontraktion", "Elastizität"],
    "Nervengewebe": ["Nervengewebe", "ZNS", "PNS"],
    "Sinnesepithelien": ["Sinnesepithel", "Netzhaut", "Stäbchen und Zapfen"]
  };
  const terms = explicitTerms.length ? explicitTerms : (topicFallbacks[card.topic] || []);
  const seen = new Set();
  return terms
    .filter((term) => definitions[term])
    .filter((term) => {
      const key = normalize(term);
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .slice(0, 4)
    .map((term) => ({ term, text: definitions[term] }));
}

function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function renderAnswer(card) {
  const lines = card.answer
    .map((line) => `<span class="answer-line">${escapeHtml(line)}</span>`)
    .join("");
  const image = card.imageAnswer
    ? `<img class="answer-image" src="${escapeHtml(card.slideImage)}" alt="Lösung als Originalfolie">`
    : "";
  const glossaryEntries = getGlossaryEntries(card);
  const glossaryHtml = glossaryEntries.length
    ? `<span class="glossary-box">
        <span class="glossary-title">Begriffe einfach erklärt</span>
        ${glossaryEntries.map((entry) => `
          <span class="glossary-entry">
            <strong>${escapeHtml(entry.term)}</strong>
            <span>${escapeHtml(entry.text)}</span>
          </span>
        `).join("")}
      </span>`
    : "";
  const sourceNote = card.sourceNote ? `<span class="source-note"><strong>Hinweis zur Skriptfolie</strong><span>${escapeHtml(card.sourceNote)}</span></span>` : "";
  return `<span class="answer-lines">${lines}${image}${glossaryHtml}${sourceNote}</span>`;
}

function renderQuestion(card) {
  return `<span>${escapeHtml(card.question)}</span>`;
}

function renderTopics() {
  const topics = ["Alle", ...Array.from(new Set(getDeckCards().map((card) => card.topic))).sort((a, b) => a.localeCompare(b, "de-AT"))];
  if (!topics.includes(state.topic)) state.topic = "Alle";
  elements.topicSelect.innerHTML = topics
    .map((topic) => `<option value="${escapeHtml(topic)}">${escapeHtml(topic)}</option>`)
    .join("");
  elements.topicSelect.value = state.topic;
}

function getCardNumber(card) {
  return state.deck === "all" ? cards.indexOf(card) + 1 : card.number;
}

